// Reproduction check: for every treatment button, run the model at the length of the study behind it and compare with the published value.
// This VERIFIES the pipeline (units, held-not-extrapolated, the 3D-driving numbers). It does not validate that a projection predicts a
// new patient: each row is the study's own result fed back through the model. See docs/validation.md for the difference.
//
//   npm run validate:projections        prints the table and rewrites docs/validation.md
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { lvMassAse } from "../src/domain/outlook/project";
import { projectAsReplacement, projectBrainTreated, projectLvhTreated } from "../src/domain/treatments/project";
import { EVIDENCE } from "../src/domain/treatments/load";
import { simulateAsReplacement, simulateBrain, simulateLvh } from "../src/domain/treatments/uncertainty";

const LVH = { ivsMm: 14, pwMm: 13, lvidMm: 46, bsaM2: 1.9 };
const BRAIN = { hippocampus: 8, ventricles: 16, cortex: 500 };
const lvm0 = lvMassAse(LVH.ivsMm, LVH.lvidMm, LVH.pwMm), lvmi0 = lvm0 / LVH.bsaM2;

interface Row { id: string; label: string; unit: string; published: number; model: number; ci?: [number, number]; band?: [number, number] }
const rows: Row[] = [];

for (const e of EVIDENCE.entries) {
  if (e.kind !== "treatment" || !e.effect) continue;
  const eff = e.effect, y = eff.evidenceYears;
  const ci: [number, number] | undefined = eff.se ? [eff.likely - 1.96 * eff.se, eff.likely + 1.96 * eff.se] : undefined;
  if (e.condition === "lvh") {
    const p = projectLvhTreated(LVH, [e.id], y, "mean");
    const b = simulateLvh(LVH, [e.id], y, "average");
    const model = eff.quantity === "lvmi_pct" ? (100 * p.lvmiChange) / lvmi0 : eff.quantity === "lvm_g" ? p.lvmiChange * LVH.bsaM2 : p.lvmiChange;
    const toUnit = (lvmi: number) => (eff.quantity === "lvmi_pct" ? (100 * (lvmi - lvmi0)) / lvmi0 : eff.quantity === "lvm_g" ? (lvmi - lvmi0) * LVH.bsaM2 : lvmi - lvmi0);
    rows.push({ id: e.id, label: e.label, unit: eff.quantity === "lvmi_pct" ? "% LVMI" : eff.quantity === "lvm_g" ? "g LV mass" : "g/m² LVMI", published: eff.likely, model, ci, band: b ? [toUnit(b.lo), toUnit(b.hi)] : undefined });
  } else if (eff.quantity === "ava_cm2") {
    const r = projectAsReplacement([e.id], y, "mean")!;
    const b = simulateAsReplacement([e.id], y, "patients");
    rows.push({ id: e.id, label: e.label, unit: "cm² (between patients)", published: eff.likely, model: r.avaCm2, ci: eff.sd ? [eff.likely - 1.96 * eff.sd, eff.likely + 1.96 * eff.sd] : undefined, band: b ? [b.lo, b.hi] : undefined });
  } else if (e.condition === "ad") {
    const nat = projectBrainTreated(BRAIN, [], y, "mean").targets, on = projectBrainTreated(BRAIN, [e.id], y, "mean").targets;
    const sim = simulateBrain(BRAIN, [], y, "average"), simOn = simulateBrain(BRAIN, [e.id], y, "average");
    if (eff.quantity === "ventricles_ml") rows.push({ id: e.id, label: e.label, unit: "mL ventricles", published: eff.likely, model: on.ventricles.projectedMl - nat.ventricles.projectedMl, ci, band: [simOn.ventricles.lo - sim.ventricles.mid, simOn.ventricles.hi - sim.ventricles.mid] });
    if (eff.quantity === "cortex_slowing_pct") {
      const lost = BRAIN.cortex - nat.cortex.projectedMl;
      rows.push({ id: e.id, label: e.label, unit: "% of natural cortex loss avoided", published: eff.likely, model: (100 * (on.cortex.projectedMl - nat.cortex.projectedMl)) / lost, ci, band: [(100 * (simOn.cortex.lo - sim.cortex.mid)) / lost, (100 * (simOn.cortex.hi - sim.cortex.mid)) / lost] });
    }
    if (eff.quantity === "hippocampus_pct") rows.push({ id: e.id, label: `${e.label} (favourable end, pace "Slower")`, unit: "% hippocampus", published: eff.best, model: (100 * (projectBrainTreated(BRAIN, [e.id], y, "slow").targets.hippocampus.projectedMl / projectBrainTreated(BRAIN, [], y, "slow").targets.hippocampus.projectedMl - 1)), ci: undefined });
  }
}

const fmt = (x: number, d = 2) => x.toFixed(d);
const lines = rows.map((r) => {
  const diff = r.model - r.published;
  const ok = Math.abs(diff) < 0.005 * Math.max(1, Math.abs(r.published));
  return `| \`${r.id}\` | ${r.label} | ${r.unit} | ${fmt(r.published)} | ${fmt(r.model)} | ${diff >= 0 ? "+" : ""}${fmt(diff, 3)} ${ok ? "✓" : "✗"} | ${r.ci ? `${fmt(r.ci[0])} to ${fmt(r.ci[1])}` : "—"} | ${r.band ? `${fmt(r.band[0])} to ${fmt(r.band[1])}` : "—"} |`;
});
const bad = rows.filter((r) => Math.abs(r.model - r.published) >= 0.005 * Math.max(1, Math.abs(r.published)));

const md = `# Reproduction check of the projections

Generated by \`npm run validate:projections\`. **Do not edit by hand.**

## What this is, and what it is not

Each row runs the model for the length of the study behind a treatment button and compares the result with the number that study
published. It **verifies the pipeline**: unit conversion (g/m², %, g, mL, cm²), the hold-after-follow-up rule, and that the numbers
driving the 3D organ are the published ones. It does **not** validate that a projection predicts the outcome of a new patient: every row
feeds a study's own result back through the model, so agreement is expected, and a ✗ means a bug.

What would validate prediction, and is not done here: projecting from a trial's baseline values and comparing with its follow-up in
patients the model never saw, and comparing with an independent cohort. The only data for that are the published summaries.

Setting: an LVH patient with IVS 14 mm, PW 13 mm, LVID 46 mm, BSA 1.9 m² (LVMI today ${fmt(lvmi0, 1)} g/m²) and brain volumes
hippocampi ${BRAIN.hippocampus} mL, ventricles ${BRAIN.ventricles} mL, cortex ${BRAIN.cortex} mL.

## Result: ${rows.length - bad.length} of ${rows.length} reproduced

| id | button | unit | published | model at study length | difference | 95 % interval from the study | Monte Carlo 95 % interval |
|---|---|---|---|---|---|---|---|
${lines.join("\n")}

**Reading the last two columns.** "95 % interval from the study" is the published CI (or ±1.96 SD between patients for the valve area).
"Monte Carlo 95 % interval" is the 2.5th to 97.5th percentile of ${2000} draws around the average effect (valve area: between patients),
expressed in the same unit. The two should agree where the study reported a normal-shaped CI; the small gaps come from asymmetric CIs
(a diuretic's 5 to 10 %) and from the model's own non-linearity.
`;
writeFileSync(resolve(__dirname, "../docs/validation.md"), md);
console.log(md.split("## Result")[1]);
if (bad.length) { console.error(`NOT REPRODUCED: ${bad.map((r) => r.id).join(", ")}`); process.exit(1); }
